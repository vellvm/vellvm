def gen_cast_poison():
    t = Dispatch("cast-poison.ll", """
; Casts and comparisons at i1 whose result is poison, with their defined
; controls.
;
; - trunc nuw iN x to i1 is poison unless x is 0 or 1 (the dropped bits must
;   be zero); trunc nsw is poison unless x is 0 or -1 (the dropped bits must
;   equal the result's sign bit).  So trunc nsw 1 and trunc nuw -1 are both
;   poison, and with both flags only 0 is defined.
; - zext nneg i1 1 and uitofp nneg i1 1 are poison: i1 1 is negative.
; - fptoui to i1 is poison unless the value truncates to 0 or 1; fptosi
;   unless it truncates to -1 or 0.  NaN and the infinities are poison.
; - icmp samesign is poison when the operands' signs differ: at i1, whenever
;   the operands differ.
; - a cast or comparison of poison is poison.""")
    for n in WIDTHS + [128]:
        for flags in TRUNC_FLAGS:
            v = f"{vname('trunc', flags)}_i{n}"
            t.section(f"{instr('trunc', flags)} i{n} to i1")
            t.add(f"define i1 @{v}(i{n} %x) {{\n  %r = {instr('trunc', flags)} i{n} %x to i1\n  ret i1 %r\n}}")
            t.asserts("i1", v, [(f"i{n} {lit}", trunc(flags, u, n)) for _, lit, u in trunc_inputs(n)]
                      + [(f"i{n} poison", P)])
    for n in WIDTHS:
        for op in ("zext", "zext nneg", "sext"):
            v = f"{op.replace(' ', '_')}_i{n}"
            t.section(f"{op} i1 to i{n}")
            t.add(f"define i{n} @{v}(i1 %x) {{\n  %r = {op} i1 %x to i{n}\n  ret i{n} %r\n}}")
            res = {"zext": [0, 1], "zext nneg": [0, P], "sext": [0, -1]}[op]
            t.asserts(f"i{n}", v, [("i1 0", res[0]), ("i1 1", res[1]), ("i1 poison", P)])
    for ft in ("float", "double"):
        for op in ("uitofp", "uitofp nneg", "sitofp"):
            v = f"{op.replace(' ', '_')}_{ft}"
            t.section(f"{op} i1 to {ft}")
            t.add(f"define {ft} @{v}(i1 %x) {{\n  %r = {op} i1 %x to {ft}\n  ret {ft} %r\n}}")
            res = {"uitofp": ["0.0", "1.0"], "uitofp nneg": ["0.0", P], "sitofp": ["0.0", "-1.0"]}[op]
            t.asserts(ft, v, [("i1 0", res[0]), ("i1 1", res[1]), ("i1 poison", P)])
    for ft in ("float", "double"):
        for op in ("fptoui", "fptosi"):
            v = f"{op}_{ft}"
            t.section(f"{op} {ft} to i1")
            t.add(f"define i1 @{v}({ft} %x) {{\n  %r = {op} {ft} %x to i1\n  ret i1 %r\n}}")
            t.asserts("i1", v, [(f"{ft} {lit}", fptoint(op == "fptosi", x)) for _, lit, x in FPS]
                      + [(f"{ft} poison", P)])
    for ss in (True, False):
        for p in PREDS:
            v = f"icmp_{'samesign_' if ss else ''}{p}"
            t.section(f"icmp {'samesign ' if ss else ''}{p}")
            t.add(fn2(v, "i1", f"icmp {'samesign ' if ss else ''}{p} i1 %a, %b"))
            args = ARGS9 if ss else ARGS9[4:]
            t.asserts("i1", v, [(f"i1 {a}, i1 {b}", icmp(p, a, b, samesign=ss)) for a, b in args])
    t.write()

