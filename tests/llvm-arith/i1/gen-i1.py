def vals(bits, ty="i1"):
    return "<" + ", ".join(f"{ty} {b}" for b in bits) + ">"


def vlit(bits, ty="i1"):
    return f"<{len(bits)} x {ty}> {vals(bits, ty)}"


def pack_fn(n):
    ls = [f"; the lanes of a <{n} x i1>, lane i in bit i (without using bitcast)",
          f"define i64 @pack{n}(<{n} x i1> %v) {{"]
    acc = None
    for i in range(n):
        ls += [f"  %e{i} = extractelement <{n} x i1> %v, i32 {i}", f"  %z{i} = zext i1 %e{i} to i64"]
        if i == 0:
            acc = "%z0"
        else:
            ls += [f"  %s{i} = shl i64 %z{i}, {i}", f"  %o{i} = or i64 {acc}, %s{i}"]
            acc = f"%o{i}"
    return "\n".join(ls + [f"  ret i64 {acc}", "}"])


