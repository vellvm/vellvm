def gen_control_poison():
    t = Dispatch("control-poison.ll", """
; Poison i1 values in select, freeze, phi, memory, and branches.
;
; - select is poison if its condition is poison, and otherwise only if the
;   *chosen* arm is.  So `select c, b, false` (a "logical and") is false when
;   c is false even if b is poison, where `and c, b` is poison.
; - freeze of a poison i1 is 0 or 1, the same value at each use: x xor x is 0
;   and x or (not x) is 1.
; - branching or switching on poison is undefined behavior.""")
    t.section("select")
    t.add("define i1 @sel(i1 %c, i1 %a, i1 %b) {\n  %r = select i1 %c, i1 %a, i1 %b\n  ret i1 %r\n}")
    t.asserts("i1", "sel", [("i1 1, i1 1, i1 poison", 1), ("i1 1, i1 0, i1 poison", 0),
                            ("i1 0, i1 poison, i1 1", 1), ("i1 0, i1 poison, i1 0", 0),
                            ("i1 1, i1 poison, i1 1", P), ("i1 0, i1 1, i1 poison", P),
                            ("i1 poison, i1 0, i1 1", P), ("i1 poison, i1 1, i1 1", P),
                            ("i1 poison, i1 poison, i1 poison", P)])
    t.add("""
; logical and / or (short-circuiting) against bitwise and / or
define i1 @logical_and(i1 %a, i1 %b) {
  %r = select i1 %a, i1 %b, i1 false
  ret i1 %r
}""")
    t.asserts("i1", "logical_and", [("i1 0, i1 poison", 0), ("i1 1, i1 poison", P), ("i1 poison, i1 0", P),
                                    ("i1 1, i1 1", 1), ("i1 1, i1 0", 0)])
    t.add("define i1 @logical_or(i1 %a, i1 %b) {\n  %r = select i1 %a, i1 true, i1 %b\n  ret i1 %r\n}")
    t.asserts("i1", "logical_or", [("i1 1, i1 poison", 1), ("i1 0, i1 poison", P), ("i1 poison, i1 1", P),
                                   ("i1 0, i1 0", 0), ("i1 0, i1 1", 1)])
    t.add("define i64 @sel_i64(i1 %c) {\n  %r = select i1 %c, i64 10, i64 20\n  ret i64 %r\n}")
    t.asserts("i64", "sel_i64", [("i1 1", 10), ("i1 0", 20), ("i1 poison", P)])
    t.section("freeze")
    t.add("""
define i1 @freeze_xor_self(i1 %x) {
  %f = freeze i1 %x
  %r = xor i1 %f, %f
  ret i1 %r
}""")
    t.asserts("i1", "freeze_xor_self", [("i1 poison", 0), ("i1 1", 0)])
    t.add("""
define i1 @freeze_or_not(i1 %x) {
  %f = freeze i1 %x
  %n = xor i1 %f, true
  %r = or i1 %f, %n
  ret i1 %r
}""")
    t.asserts("i1", "freeze_or_not", [("i1 poison", 1), ("i1 0", 1)])
    t.add("""
; a frozen poison is a real i1, so it may be branched on
define i64 @freeze_br(i1 %x) {
  %f = freeze i1 %x
  br i1 %f, label %t, label %e
t:
  ret i64 7
e:
  ret i64 7
}""")
    t.asserts("i64", "freeze_br", [("i1 poison", 7), ("i1 1", 7)])
    t.add("define i1 @freeze(i1 %x) {\n  %r = freeze i1 %x\n  ret i1 %r\n}")
    t.asserts("i1", "freeze", [("i1 0", 0), ("i1 1", 1)])
    t.add("""
; without the freeze, the same computations stay poison
define i1 @xor_self(i1 %x) {
  %r = xor i1 %x, %x
  ret i1 %r
}""")
    t.asserts("i1", "xor_self", [("i1 poison", P), ("i1 1", 0)])
    t.section("phi, calls, memory")
    t.add("""
define i1 @phi(i1 %c, i1 %a, i1 %b) {
entry:
  br i1 %c, label %t, label %e
t:
  br label %join
e:
  br label %join
join:
  %r = phi i1 [ %a, %t ], [ %b, %e ]
  ret i1 %r
}""")
    t.asserts("i1", "phi", [("i1 1, i1 poison, i1 0", P), ("i1 0, i1 poison, i1 0", 0),
                            ("i1 1, i1 1, i1 poison", 1), ("i1 0, i1 1, i1 poison", P)])
    t.add("""
define i1 @id(i1 %x) {
  ret i1 %x
}

define i1 @through_call(i1 %x) {
  %r = call i1 @id(i1 %x)
  ret i1 %r
}""")
    t.asserts("i1", "through_call", [("i1 poison", P), ("i1 1", 1)])
    t.add("""
define i1 @through_memory(i1 %x) {
  %p = alloca i1
  store i1 %x, ptr %p
  %r = load i1, ptr %p
  ret i1 %r
}""")
    t.asserts("i1", "through_memory", [("i1 poison", P), ("i1 1", 1), ("i1 0", 0)])
    t.add("""
; a poison i1 field does not poison its neighbours
define i1 @struct_field(i1 %x, i32 %i) {
  %s = insertvalue { i1, i1 } { i1 true, i1 true }, i1 %x, 0
  %p = alloca { i1, i1 }
  store { i1, i1 } %s, ptr %p
  %q = getelementptr { i1, i1 }, ptr %p, i64 0, i32 1
  %c = icmp eq i32 %i, 0
  %a = select i1 %c, ptr %p, ptr %q
  %r = load i1, ptr %a
  ret i1 %r
}""")
    t.asserts("i1", "struct_field", [("i1 poison, i32 0", P), ("i1 poison, i32 1", 1), ("i1 0, i32 0", 0)])
    t.section("branching on poison")
    t.add("""
define i64 @br(i1 %c) {
  br i1 %c, label %t, label %e   ; <- UB @br
t:
  ret i64 10
e:
  ret i64 20
}""")
    t.asserts("i64", "br", [("i1 1", 10), ("i1 0", 20), ("i1 poison", UB)])
    t.add("""
; ... even when both targets are the same block
define i64 @br_same(i1 %c) {
  br i1 %c, label %t, label %t   ; <- UB @br_same
t:
  ret i64 10
}""")
    t.asserts("i64", "br_same", [("i1 1", 10), ("i1 poison", UB)])
    t.add("""
define i64 @switch(i1 %c) {
  switch i1 %c, label %d [ i1 0, label %zero
                           i1 1, label %one ]   ; <- UB @switch
zero:
  ret i64 100
one:
  ret i64 101
d:
  ret i64 102
}""")
    t.asserts("i64", "switch", [("i1 0", 100), ("i1 1", 101), ("i1 poison", UB)])
    t.add("""
; the branch is on a flag violation computed in the function
define i64 @br_mul_nsw(i1 %a, i1 %b) {
  %m = mul nsw i1 %a, %b
  br i1 %m, label %t, label %e   ; <- UB @br_mul_nsw
t:
  ret i64 10
e:
  ret i64 20
}""")
    t.asserts("i64", "br_mul_nsw", [("i1 0, i1 1", 20), ("i1 1, i1 0", 20), ("i1 1, i1 1", UB)])
    t.add("""
define i64 @br_trunc_nuw(i8 %x) {
  %c = trunc nuw i8 %x to i1
  br i1 %c, label %t, label %e   ; <- UB @br_trunc_nuw
t:
  ret i64 10
e:
  ret i64 20
}""")
    t.asserts("i64", "br_trunc_nuw", [("i8 0", 20), ("i8 1", 10), ("i8 2", UB), ("i8 -1", UB)])
    t.add("""
define i64 @br_zext_nneg(i1 %x) {
  %w = zext nneg i1 %x to i8
  %c = icmp eq i8 %w, 0
  br i1 %c, label %t, label %e   ; <- UB @br_zext_nneg
t:
  ret i64 10
e:
  ret i64 20
}""")
    t.asserts("i64", "br_zext_nneg", [("i1 0", 10), ("i1 1", UB)])
    t.write()

