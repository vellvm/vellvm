def gen_vector_poison():
    t = Dispatch("vector-poison.ll", f"""
; Poison in individual lanes of <N x i1> vectors.
;
; Flags are checked lane by lane: a lane that violates its flag is poison and
; the others are unaffected.  As in vector-ops.ll, the lane-wise cases run an
; operator on a = {vlit(VA)} and b = {vlit(VB)},
; so lane i is the i-th row of the truth table; `@f(i32 i)` returns lane i,
; and `@f_all()` the whole vector.""")
    for op, flags in BINOPS:
        if op in DIVS:
            continue
        rs = [binop(op, flags, a, b) for a, b in PAIRS]
        if P not in rs:
            continue
        v = "v_" + vname(op, flags)
        t.section(instr(op, flags))
        t.add(f"define <4 x i1> @{v}_all() {{\n  %r = {instr(op, flags)} {vlit(VA)}, {vals(VB)}\n  ret <4 x i1> %r\n}}\n\n"
              f"define i1 @{v}(i32 %i) {{\n  %v = call <4 x i1> @{v}_all()\n"
              f"  %r = extractelement <4 x i1> %v, i32 %i\n  ret i1 %r\n}}")
        t.asserts("i1", v, [(f"i32 {i}", r) for i, r in enumerate(rs)])
        t.asserts("<4 x i1>", v + "_all", [("", P if all(r == P for r in rs) else vals(rs))])
    t.section("casts")
    lanes = [0, 1, 2, -1]
    for flags in ("nuw", "nsw", "nuw nsw"):
        v = "v_" + vname("trunc", flags)
        rs = [trunc(flags, x & 255, 8) for x in lanes]
        t.add(f"define <4 x i1> @{v}_all() {{\n  %r = trunc {flags} {vlit(lanes, 'i8')} to <4 x i1>\n  ret <4 x i1> %r\n}}\n\n"
              f"define i1 @{v}(i32 %i) {{\n  %v = call <4 x i1> @{v}_all()\n"
              f"  %r = extractelement <4 x i1> %v, i32 %i\n  ret i1 %r\n}}")
        t.asserts("i1", v, [(f"i32 {i}", r) for i, r in enumerate(rs)])
        t.asserts("<4 x i1>", v + "_all", [("", vals(rs))])
    t.add("""
define <2 x i8> @v_zext_nneg_all() {
  %r = zext nneg <2 x i1> <i1 0, i1 1> to <2 x i8>
  ret <2 x i8> %r
}

define i8 @v_zext_nneg(i32 %i) {
  %v = call <2 x i8> @v_zext_nneg_all()
  %r = extractelement <2 x i8> %v, i32 %i
  ret i8 %r
}""")
    t.asserts("i8", "v_zext_nneg", [("i32 0", 0), ("i32 1", P)])
    t.asserts("<2 x i8>", "v_zext_nneg_all", [("", "<i8 0, i8 poison>")])
    t.add("""
define <4 x i1> @v_icmp_samesign_ult_all() {
  %r = icmp samesign ult <4 x i1> <i1 0, i1 0, i1 1, i1 1>, <i1 0, i1 1, i1 0, i1 1>
  ret <4 x i1> %r
}""")
    t.asserts("<4 x i1>", "v_icmp_samesign_ult_all", [("", "<i1 0, i1 poison, i1 poison, i1 0>")])
    t.section("select and element access")
    t.add("""
; a poison lane of the condition poisons only that lane
define i1 @v_select_poison_cond(i32 %i) {
  %v = select <2 x i1> <i1 poison, i1 1>, <2 x i1> <i1 1, i1 1>, <2 x i1> <i1 0, i1 0>
  %r = extractelement <2 x i1> %v, i32 %i
  ret i1 %r
}""")
    t.asserts("i1", "v_select_poison_cond", [("i32 0", P), ("i32 1", 1)])
    t.add("""
; an out-of-range index is poison
define i1 @v_extract(i32 %i) {
  %r = extractelement <2 x i1> <i1 0, i1 1>, i32 %i
  ret i1 %r
}""")
    t.asserts("i1", "v_extract", [("i32 0", 0), ("i32 1", 1), ("i32 2", P), ("i32 -1", P), ("i32 poison", P)])
    t.add("""
; ... and makes the whole vector poison in insertelement
define i1 @v_insert(i32 %i) {
  %v = insertelement <2 x i1> <i1 0, i1 1>, i1 1, i32 %i
  %r = extractelement <2 x i1> %v, i32 1
  ret i1 %r
}""")
    t.asserts("i1", "v_insert", [("i32 0", 1), ("i32 2", P)])
    t.add("""
; a poison lane survives a round trip through memory without spreading
define i1 @v_memory(i32 %i) {
  %p = alloca <4 x i1>
  store <4 x i1> <i1 1, i1 poison, i1 0, i1 1>, ptr %p
  %v = load <4 x i1>, ptr %p
  %r = extractelement <4 x i1> %v, i32 %i
  ret i1 %r
}""")
    t.asserts("i1", "v_memory", [("i32 0", 1), ("i32 1", P), ("i32 2", 0), ("i32 3", 1)])
    t.write()

