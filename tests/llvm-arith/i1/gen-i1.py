PRINT_ALL = ["binop.ll", "icmp.ll", "cast.ll", "control.ll", "switch-literals.ll", "memory.ll", "vector-ops.ll", "intrinsics.ll"]
DISPATCH = ["binop-poison.ll", "div-rem-ub.ll", "cast-poison.ll", "control-poison.ll",
            "vector-poison.ll", "intrinsics-poison.ll"]


def run(cmd):
    p = subprocess.run(cmd, capture_output=True, text=True, errors="replace", timeout=120)
    return p.returncode, p.stdout, p.stderr


def norm(ty, s):
    """Normalise a literal (from an ASSERT or from llubi --verbose) for comparison."""
    s = s.strip()
    s = re.sub(r"<\d+ x \w+>\s+", "", s)                               # drop type prefixes
    s = re.sub(r"\b(i\d+|float|double)\s+", "", s)
    s = s.replace("true", "1").replace("false", "0")
    s = re.sub(r"\bT\b", "1", s)
    s = re.sub(r"\bF\b", "0", s)
    s = re.sub(r"[<>{}\s]", "", s)

    def num(m):
        x = m.group(0)
        if re.search(r"[.e]", x):
            return repr(float(x))
        v = int(x)
        m_ = re.fullmatch(r"(?:<\d+ x )?i(\d+)>?", ty)
        return str(v & ((1 << int(m_[1])) - 1)) if m_ else str(v)
    return re.sub(r"-?\d+(?:\.\d+)?(?:e[+-]?\d+)?", num, s)


def check(clang="clang", llubi="llubi"):
    bad = total = 0
    with tempfile.TemporaryDirectory() as tmp:
        for name in PRINT_ALL:
            path, exe = os.path.join(HERE, name), os.path.join(tmp, "a.out")
            want = [(a["fn"], a["expected"].split()[-1]) for a in gen.parse_asserts(open(path).read())]
            for opt in ("-O0", "-O2"):
                rc, out, err = run([clang, "-w", opt, path, "-o", exe])
                if rc:
                    print(f"{name}: clang {opt} failed:\n{err}")
                    bad += 1
                    continue
                rc, out, err = run([exe])
                got = dict(re.findall(r"^(\S+)\(\) = (-?\d+)$", out, re.M))
                for fn, e in want:
                    total += 1
                    if got.get(fn) != e:
                        bad += 1
                        print(f"{name} clang {opt}: {fn}: asserted {e}, got {got.get(fn)}")
            print(f"{name}: {len(want)} cases checked against clang -O0 and -O2")
        for name in DISPATCH:
            path, exe = os.path.join(HERE, name), os.path.join(tmp, "a.out")
            asserts = gen.parse_asserts(open(path).read())
            rc, out, err = run([clang, "-w", "-O0", path, "-o", exe])
            if rc:
                print(f"{name}: clang failed:\n{err}")
                bad += 1
            for n, a in enumerate(asserts):
                total += 1
                rc, out, err = run([llubi, "--verbose", f"--entry-function=ub_case_{n}", path])
                o = out + err
                want = UB if a["kind"] == "UB" else norm(a["ty"], a["expected"])
                if "Immediate UB detected" in o:
                    loc = re.search(r"#0 .* at @\S+ \S+?:(\d+)", o)
                    got = UB
                    if a["kind"] == "UB" and loc and int(loc[1]) != a["ubline"]:
                        got = f"UB at line {loc[1]}, not {a['ubline']}"
                        want = "UB at the asserted line"
                else:
                    m = re.findall(r"^  %r = call .* => (.*)$", o, re.M)
                    got = norm(a["ty"], m[-1]) if m else f"?? {o.strip()[-200:]}"
                if got != want:
                    bad += 1
                    print(f"{name} llubi: case {n}: {a['src']}: got {got}")
                    continue
                # a defined result must also be what the native build prints
                if want not in (UB,) and P not in want and not rc:
                    rc2, out2, _ = run([exe, str(n)])
                    m = re.search(rf"case {n}: returned(.*)", out2)
                    vals = m[1].split() if m else None
                    t_ = re.fullmatch(r"(?:<\d+ x )?i(\d+)>?", a["ty"])
                    if vals and t_:
                        vals = ",".join(str(int(v) & ((1 << int(t_[1])) - 1)) for v in vals)
                    elif vals:
                        vals = ",".join(repr(float(v)) for v in vals)
                    if vals != want:
                        bad += 1
                        print(f"{name} native: case {n}: {a['src']}: printed {vals}")
            print(f"{name}: {len(asserts)} cases checked against llubi (and clang -O0 where defined)")
    print(f"{total} cases, {bad} disagreements")
    return bad


if __name__ == "__main__":
    if sys.argv[1:2] == ["--check"]:
        sys.exit(1 if check() else 0)
