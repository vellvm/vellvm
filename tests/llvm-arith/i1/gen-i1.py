def gen_intrinsics_poison():
    t = Dispatch("intrinsics-poison.ll", """
; Integer intrinsics at i1 whose result is poison, with defined controls.
;
; - abs(1, is_int_min_poison = true): 1 is INT_MIN.
; - ctlz / cttz (0, is_zero_poison = true).
; - sshl.sat / ushl.sat by 1: a shift by the bit width.
; - any poison argument.""")
    for k, (sig, f) in UNARY.items():
        t.section(k)
        t.add(f"declare {sig}\n\ndefine i1 @{k}(i1 %x, i1 %strict) {{\n"
              f"  %t = call i1 @llvm.{k}.i1(i1 %x, i1 true)\n  %f = call i1 @llvm.{k}.i1(i1 %x, i1 false)\n"
              "  %r = select i1 %strict, i1 %t, i1 %f\n  ret i1 %r\n}")
        t.asserts("i1", k, [(f"i1 {x}, i1 {s}", f(x, s)) for s in (1, 0) for x in (0, 1)]
                  + [("i1 poison, i1 0", P)])
    for k in ("sshl.sat", "ushl.sat", "smax", "umin", "sadd.sat"):
        n = uname(k)
        t.section(k)
        t.add(f"declare i1 @llvm.{k}.i1(i1, i1)\n\n" + fn2(n, "i1", f"call i1 @llvm.{k}.i1(i1 %a, i1 %b)"))
        t.asserts("i1", n, [(f"i1 {a}, i1 {b}", P if P in (a, b) else SAT[k](a, b)) for a, b in ARGS9[:6]])
    t.section("overflow of poison")
    t.add("""
declare { i1, i1 } @llvm.smul.with.overflow.i1(i1, i1)

define i1 @smul_overflow_flag(i1 %a, i1 %b) {
  %p = call { i1, i1 } @llvm.smul.with.overflow.i1(i1 %a, i1 %b)
  %r = extractvalue { i1, i1 } %p, 1
  ret i1 %r
}""")
    t.asserts("i1", "smul_overflow_flag", [("i1 1, i1 1", 1), ("i1 1, i1 0", 0), ("i1 poison, i1 0", P)])
    t.write()

