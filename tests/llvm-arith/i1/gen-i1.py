def gen_control():
    t = PrintAll("control.ll", """
; i1 as a value that flows through a program: literals, select, br, phi,
; switch, calls, and small arithmetic identities.
;
; - `true`, `1` and `-1` are the same i1 literal.
; - at i1, negation is the identity (0 - x = x), x + x = 0, x * x = x, and
;   x + 1 = x - 1 = not x.
;
;   clang -w tests/llvm-arith/i1/control.ll -o a.out && ./a.out""")
    t.section("literals")
    for name, lit, ext, e in [("lit_true", "true", "zext", 1), ("lit_false", "false", "zext", 0),
                              ("lit_1", "1", "zext", 1), ("lit_0", "0", "zext", 0),
                              ("lit_m1", "-1", "zext", 1), ("lit_true_sext", "true", "sext", -1),
                              ("lit_1_sext", "1", "sext", -1), ("lit_m1_sext", "-1", "sext", -1)]:
        t.case(name, e, f"  %z = {ext} i1 {lit} to i64\n  ret i64 %z")
    t.case("lit_m1_eq_1", 1, "  %c = icmp eq i1 -1, 1\n  %z = zext i1 %c to i64\n  ret i64 %z")
    t.case("lit_true_eq_m1", 1, "  %c = icmp eq i1 true, -1\n  %z = zext i1 %c to i64\n  ret i64 %z")

    t.section("select")
    t.add("define i1 @sel(i1 %c, i1 %a, i1 %b) {\n  %r = select i1 %c, i1 %a, i1 %b\n  ret i1 %r\n}")
    for c in (0, 1):
        for a, b in PAIRS:
            t.call(f"sel_{c}_{a}_{b}", a if c else b, "i1", "sel", f"i1 {c}, i1 {a}, i1 {b}")
    t.add("define i64 @sel_i64(i1 %c) {\n  %r = select i1 %c, i64 10, i64 20\n  ret i64 %r\n}")
    t.call("sel_i64_0", 20, "i64", "sel_i64", "i1 0")
    t.call("sel_i64_1", 10, "i64", "sel_i64", "i1 1")
    t.call("sel_i64_m1", 10, "i64", "sel_i64", "i1 -1")

    t.section("br, phi, switch")
    t.add("""
define i64 @br(i1 %c) {
  br i1 %c, label %t, label %f
t:
  ret i64 10
f:
  ret i64 20
}

; a phi of i1 constants: not %c
define i1 @phi_not(i1 %c) {
entry:
  br i1 %c, label %a, label %b
a:
  br label %join
b:
  br label %join
join:
  %r = phi i1 [ false, %a ], [ true, %b ]
  ret i1 %r
}

define i64 @switch(i1 %c) {
  switch i1 %c, label %d [ i1 0, label %zero
                           i1 1, label %one ]
zero:
  ret i64 100
one:
  ret i64 101
d:
  ret i64 102
}

; only 1 has a case: 0 takes the default
define i64 @switch_default(i1 %c) {
  switch i1 %c, label %d [ i1 1, label %one ]
one:
  ret i64 101
d:
  ret i64 102
}

; the case value -1 is the value 1
define i64 @switch_m1(i1 %c) {
  switch i1 %c, label %d [ i1 -1, label %one ]
one:
  ret i64 101
d:
  ret i64 102
}

; an i1 counter wraps after two increments
define i64 @loop_wrap() {
entry:
  br label %loop
loop:
  %i = phi i1 [ 0, %entry ], [ %inc, %loop ]
  %n = phi i64 [ 0, %entry ], [ %n.next, %loop ]
  %inc = add i1 %i, 1
  %n.next = add i64 %n, 1
  %done = icmp eq i1 %inc, 0
  br i1 %done, label %exit, label %loop
exit:
  ret i64 %n.next
}""")
    t.tests.append(("loop_wrap", 2))
    for c in (0, 1):
        t.call(f"br_{c}", 10 if c else 20, "i64", "br", f"i1 {c}")
        t.call(f"phi_not_{c}", 1 - c, "i1", "phi_not", f"i1 {c}")
        t.call(f"switch_{c}", 100 + c, "i64", "switch", f"i1 {c}")
        t.call(f"switch_default_{c}", 101 if c else 102, "i64", "switch_default", f"i1 {c}")
        t.call(f"switch_m1_{c}", 101 if c else 102, "i64", "switch_m1", f"i1 {c}")

    t.section("calls")
    t.add("""
define i1 @id(i1 %x) {
  ret i1 %x
}

define zeroext i1 @id_zeroext(i1 zeroext %x) {
  ret i1 %x
}

define signext i1 @id_signext(i1 signext %x) {
  ret i1 %x
}""")
    for f in ("id", "id_zeroext", "id_signext"):
        for x in (0, 1):
            t.call(f"{f}_{x}", x, "i1", f, f"i1 {x}")
