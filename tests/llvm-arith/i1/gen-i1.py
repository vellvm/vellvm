#!/usr/bin/env python3
"""Generate (and check) the i1 arithmetic test suite in this directory.

    python3 tests/llvm-arith/i1/gen-i1.py            # (re)write the .ll files
    python3 tests/llvm-arith/i1/gen-i1.py --check    # run them under clang and llubi

i1 is the degenerate integer width: its only values are 0 and 1, read as
0 and -1 when signed, so INT_MIN = -1 = "all ones" and INT_MAX = 0.  That makes
almost every flag and every corner case of the LangRef reachable with a
handful of inputs, and the suite is exhaustive over them: every operation is
run on *every* pair of i1 inputs.

Expected results come from the small reference model of the LangRef in this
file (`binop`, `icmp`, `trunc`, ...), not from running a tool; `--check` then
confirms the model against clang (defined results) and llubi (poison and UB).

Two kinds of file are written, both with tests/gen.py:

- print-all files (binop.ll, icmp.ll, cast.ll, control.ll, memory.ll,
  vector-ops.ll, intrinsics.ll) hold only cases with a *defined* result.
  Every case is an argument-free function returning i64, `main` prints them
  all, and there is one `ASSERT EQ` per case, as in tests/ll/gep-layout.ll:

      clang -w tests/llvm-arith/i1/binop.ll -o a.out && ./a.out

- dispatch files (binop-poison.ll, div-rem-ub.ll, cast-poison.ll,
  control-poison.ll, vector-poison.ll, intrinsics-poison.ll) hold the cases
  whose result is poison or undefined behavior, next to defined controls.
  They assert on parameterised functions directly, and end with the
  `tests/gen.py --dispatch` tail, as in tests/ub: `./a.out N` runs case N
  alone, and `llubi --entry-function=ub_case_N FILE` is the oracle that can
  actually see poison and UB.  tests/ub/compare.py accepts these files too.
"""
import math
import os
import re
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
TESTS = os.path.dirname(os.path.dirname(HERE))
sys.dont_write_bytecode = True
sys.path.insert(0, TESTS)
import gen  # noqa: E402  (tests/gen.py)

P, UB = "poison", "UB"
GENERATED = "; Generated by tests/llvm-arith/i1/gen-i1.py -- edit the generator, not this file."

# ===================================================================== model


def sgn(x, n=1):
    """The signed reading of the n-bit value x."""
    return x - (1 << n) if x >> (n - 1) else x


def in_s(v, n):
    return -(1 << (n - 1)) <= v < (1 << (n - 1))


def tdiv(a, b):
    """Division rounding toward zero."""
    q = abs(a) // abs(b)
    return q if (a < 0) == (b < 0) else -q


def binop(op, flags, a, b, n=1):
    """LangRef semantics of `op flags iN a, b`: a value, P, or UB.
    a and b are unsigned n-bit values or P."""
    m = (1 << n) - 1
    if op in ("udiv", "sdiv", "urem", "srem"):
        if b == P or b == 0:
            return UB
        if op in ("sdiv", "srem") and sgn(b, n) == -1 and (a == P or sgn(a, n) == -(1 << (n - 1))):
            return UB  # INT_MIN / -1, which a poison dividend may be
        if a == P:
            return P
        if op == "udiv":
            return P if "exact" in flags and a % b else a // b
        if op == "urem":
            return a % b
        q = tdiv(sgn(a, n), sgn(b, n))
        r = sgn(a, n) - q * sgn(b, n)
        if op == "sdiv":
            return P if "exact" in flags and r else q & m
        return r & m
    if a == P or b == P:
        return P
    if op in ("add", "sub", "mul"):
        f = {"add": lambda x, y: x + y, "sub": lambda x, y: x - y, "mul": lambda x, y: x * y}[op]
        if "nuw" in flags and not 0 <= f(a, b) <= m:
            return P
        if "nsw" in flags and not in_s(f(sgn(a, n), sgn(b, n)), n):
            return P
        return f(a, b) & m
    if op == "shl":
        if b >= n:
            return P
        if "nuw" in flags and (a << b) > m:
            return P
        if "nsw" in flags and not in_s(sgn(a, n) << b, n):
            return P
        return (a << b) & m
    if op in ("lshr", "ashr"):
        if b >= n:
            return P
        if "exact" in flags and a & ((1 << b) - 1):
            return P
        return (a >> b) if op == "lshr" else (sgn(a, n) >> b) & m
    if op == "or" and "disjoint" in flags and a & b:
        return P
    return {"and": a & b, "or": a | b, "xor": a ^ b}[op]


PREDS = ["eq", "ne", "ugt", "uge", "ult", "ule", "sgt", "sge", "slt", "sle"]


def icmp(pred, a, b, n=1, samesign=False):
    if a == P or b == P:
        return P
    if samesign and (sgn(a, n) < 0) != (sgn(b, n) < 0):
        return P
    if pred[0] == "s":
        a, b = sgn(a, n), sgn(b, n)
    return int({"eq": a == b, "ne": a != b, "gt": a > b, "ge": a >= b,
                "lt": a < b, "le": a <= b}[pred[-2:]])


def trunc(flags, x, n):
    """`trunc flags iN x to i1`, x unsigned."""
    if x == P:
        return P
    if "nuw" in flags and x > 1:
        return P
    if "nsw" in flags and sgn(x, n) not in (0, -1):
        return P
    return x & 1


def fptoint(signed, x):
    """`fptosi/fptoui x to i1`."""
    if x == P or math.isnan(x) or math.isinf(x):
        return P
    t = math.trunc(x)
    if signed:
        return t & 1 if -1 <= t <= 0 else P
    return t if 0 <= t <= 1 else P


BINOPS = ([(op, f) for op in ("add", "sub", "mul", "shl") for f in ("", "nuw", "nsw", "nuw nsw")]
          + [(op, f) for op in ("udiv", "sdiv", "lshr", "ashr") for f in ("", "exact")]
          + [("urem", ""), ("srem", ""), ("and", ""), ("or", ""), ("or", "disjoint"), ("xor", "")])
PAIRS = [(a, b) for a in (0, 1) for b in (0, 1)]
DIVS = ("udiv", "sdiv", "urem", "srem")


def vname(op, flags):
    return "_".join([op] + flags.split())


def instr(op, flags):
    return f"{op} {flags}".strip()


def lab(v):
    """A value as part of a function name."""
    return "p" if v == P else f"m{-v}" if v < 0 else str(v)

# =================================================================== writers


class PrintAll:
    """A tests/ll/gep-layout.ll style file: defined results only."""

    def __init__(self, name, header):
        self.name, self.out, self.tests = name, [header.strip("\n"), ";", GENERATED, ""], []

    def add(self, text):
        self.out.append(text.strip("\n") + "\n")

    def section(self, title):
        self.out.append(f"; {'-' * (70 - len(title))} {title}\n")

    def case(self, name, expected, body):
        """An argument-free i64 function with the given body."""
        self.add(f"define i64 @{name}() {{\n{body.strip(chr(10))}\n}}")
        self.tests.append((name, expected))

    def call(self, name, expected, ty, fn, args, ext="zext"):
        """A case that calls `ty @fn(args)` and widens the result to i64.
        With zext, `expected` is the unsigned value of the result."""
        conv = "  ret i64 %r" if ty == "i64" else f"  %z = {ext} {ty} %r to i64\n  ret i64 %z"
        self.case(name, expected, f"  %r = call {ty} @{fn}({args})\n{conv}")

    def write(self):
        names = [t[0] for t in self.tests]
        assert len(names) == len(set(names)), self.name
        with open(os.path.join(HERE, self.name), "w") as f:
            f.write("\n".join(self.out) + gen.tail([(n, str(e)) for n, e in self.tests]))


class Dispatch:
    """A tests/ub style file: poison and UB, with defined controls."""

    def __init__(self, name, header):
        self.name, self.out, self.ub = name, [header.strip("\n"), ";", GENERATED, ""], False

    def add(self, text):
        self.out.append(text.strip("\n") + "\n")

    def section(self, title):
        self.out.append(f"; {'-' * (70 - len(title))} {title}\n")

    def asserts(self, ty, fn, cases):
        """cases: [(args, expected)], expected a literal, P or UB."""
        ls = []
        for args, e in cases:
            if e == UB:
                self.ub = True
                ls.append(f"; ASSERT UB ?: call {ty} @{fn}({args})")
            else:
                ls.append(f"; ASSERT EQ: {ty} {e} = call {ty} @{fn}({args})")
        self.out.append("\n".join(ls) + "\n")

    def write(self):
        path = os.path.join(HERE, self.name)
        with open(path, "w") as f:
            f.write("\n".join(self.out))
        if self.ub:
            subprocess.run([sys.executable, os.path.join(TESTS, "ub", "fill-ub-lines.py"), path], check=True)
        gen.dispatch([path])


def fn2(name, ty, body, marker=False):
    """define ty @name(i1 %a, i1 %b) computing `body`."""
    m = f"   ; <- UB @{name}" if marker else ""
    return f"define {ty} @{name}(i1 %a, i1 %b) {{\n  %r = {body}{m}\n  ret {ty} %r\n}}"

# ================================================================== binop.ll


def gen_binop():
    t = PrintAll("binop.ll", """
; i1 binary operators: every operator, with every combination of its flags,
; on every pair of i1 inputs for which the result is defined.
;
; The cases that are missing from a truth table here are the ones whose
; result is poison (binop-poison.ll) or undefined behavior (div-rem-ub.ll).
;
; Things that are particular to i1 (signed range {-1, 0}, 1 is -1):
; - add nsw 1, 1 and add nuw 1, 1 both overflow;
; - sub nsw 0, 1 is 0 - (-1) = 1, which overflows;
; - mul nsw 1, 1 is (-1) * (-1) = 1, which overflows, while mul nuw 1, 1 is 1;
; - any shift by 1 is a shift by the bit width;
; - sdiv/srem 1, 1 is INT_MIN / -1.
;
; Run natively with
;   clang -w tests/llvm-arith/i1/binop.ll -o a.out && ./a.out
; and compare the output with the ASSERTs at the bottom.""")
    for op, flags in BINOPS:
        v = vname(op, flags)
        rows = [(a, b, binop(op, flags, a, b)) for a, b in PAIRS]
        t.section(instr(op, flags))
        gone = [f"{a},{b} is {r}" for a, b, r in rows if r in (P, UB)]
        if gone:
            t.out.append("; " + "; ".join(gone) + "\n")
        t.add(fn2(v, "i1", f"{instr(op, flags)} i1 %a, %b"))
        for a, b, r in rows:
            if r not in (P, UB):
                t.call(f"{v}_{a}_{b}", r, "i1", v, f"i1 {a}, i1 {b}")
    t.write()

# =================================================================== icmp.ll


def gen_icmp():
    t = PrintAll("icmp.ll", """
; icmp at i1: every predicate on every pair of inputs.
;
; The signed predicates read 1 as -1, so `icmp slt i1 1, 0` is true and
; `icmp sgt i1 1, 0` is false -- the opposite of the unsigned ones.
;
; `icmp samesign` is poison when the operands' signs differ, which at i1 means
; whenever the operands differ; the cases here are the defined ones (a = b),
; the rest are in cast-poison.ll.
;
;   clang -w tests/llvm-arith/i1/icmp.ll -o a.out && ./a.out""")
    for ss in (False, True):
        for p in PREDS:
            v = f"icmp_{'samesign_' if ss else ''}{p}"
            t.section(f"icmp {'samesign ' if ss else ''}{p}")
            t.add(fn2(v, "i1", f"icmp {'samesign ' if ss else ''}{p} i1 %a, %b"))
            for a, b in PAIRS:
                r = icmp(p, a, b, samesign=ss)
                if r != P:
                    t.call(f"{v}_{a}_{b}", r, "i1", v, f"i1 {a}, i1 {b}")
    t.write()

# =================================================================== cast.ll

WIDTHS = [2, 8, 32, 64]
TRUNC_FLAGS = ["", "nuw", "nsw", "nuw nsw"]


def trunc_inputs(n):
    """[(label, literal, unsigned value)] of iN inputs worth truncating."""
    seen, out = set(), []
    for label, v in [("0", 0), ("1", 1), ("2", 2), ("3", 3), ("m1", -1), ("m2", -2),
                     ("min", -(1 << (n - 1))), ("max", (1 << (n - 1)) - 1)]:
        u = v & ((1 << n) - 1)
        if u not in seen:
            seen.add(u)
            out.append((label, sgn(u, n), u))
    return out


# (label, LLVM literal, value)
FPS = [("0", "0.0", 0.0), ("m0", "-0.0", -0.0), ("0_5", "0.5", 0.5), ("m0_5", "-0.5", -0.5),
       ("1", "1.0", 1.0), ("m1", "-1.0", -1.0), ("1_5", "1.5", 1.5), ("m1_5", "-1.5", -1.5),
       ("2", "2.0", 2.0), ("m2", "-2.0", -2.0),
       ("nan", "0x7FF8000000000000", math.nan), ("inf", "0x7FF0000000000000", math.inf),
       ("minf", "0xFFF0000000000000", -math.inf)]

FP_BITS = {("double", 1.0): 0x3FF0000000000000, ("double", -1.0): 0xBFF0000000000000 - (1 << 64),
           ("double", 0.0): 0, ("float", 1.0): 0x3F800000, ("float", -1.0): 0xBF800000, ("float", 0.0): 0}


def gen_cast():
    t = PrintAll("cast.ll", """
; Casts to and from i1, on the inputs for which the result is defined
; (the poison cases are in cast-poison.ll).
;
; - trunc iN to i1 keeps the low bit.  `trunc nuw` needs the dropped bits to
;   be zero, so only 0 and 1 survive; `trunc nsw` needs them to be copies of
;   the result's sign bit, so only 0 and -1 survive (trunc nsw of 1 is
;   poison); with both flags only 0 survives.
; - zext i1 1 is 1, sext i1 1 is -1.  `zext nneg` needs a non-negative
;   operand, and i1 1 is negative, so only `zext nneg i1 0` is defined.
; - uitofp i1 1 is 1.0, sitofp i1 1 is -1.0; `uitofp nneg` is like zext nneg.
; - fptoui to i1 is defined when the value truncates to 0 or 1, fptosi when
;   it truncates to -1 or 0 (so fptosi 1.0 is poison and fptosi -1.0 is true).
;
; Each case returns its result zero-extended to i64 (so sext i1 1 to i8 shows
; as 255); floating-point results are returned as their bit pattern.
;
;   clang -w tests/llvm-arith/i1/cast.ll -o a.out && ./a.out""")
    for n in WIDTHS:
        for flags in TRUNC_FLAGS:
            v = f"{vname('trunc', flags)}_i{n}"
            t.section(f"{instr('trunc', flags)} i{n} to i1")
            t.add(f"define i1 @{v}(i{n} %x) {{\n  %r = {instr('trunc', flags)} i{n} %x to i1\n  ret i1 %r\n}}")
            for label, lit, u in trunc_inputs(n):
                r = trunc(flags, u, n)
                if r != P:
                    t.call(f"{v}_{label}", r, "i1", v, f"i{n} {lit}")
    for n in WIDTHS:
        for op in ("zext", "zext nneg", "sext"):
            v = f"{op.replace(' ', '_')}_i{n}"
            t.section(f"{op} i1 to i{n}")
            t.add(f"define i{n} @{v}(i1 %x) {{\n  %r = {op} i1 %x to i{n}\n  ret i{n} %r\n}}")
            for x in (0, 1):
                if op == "zext nneg" and x:
                    continue
                r = x if op != "sext" else (-x) & ((1 << n) - 1)
                t.call(f"{v}_{x}", sgn(r, 64) if n == 64 else r, f"i{n}", v, f"i1 {x}")
    for ft in ("float", "double"):
        bits = "i32" if ft == "float" else "i64"
        for op in ("uitofp", "uitofp nneg", "sitofp"):
            v = f"{op.replace(' ', '_')}_{ft}"
            t.section(f"{op} i1 to {ft}")
            t.add(f"define {bits} @{v}(i1 %x) {{\n  %f = {op} i1 %x to {ft}\n"
                  f"  %r = bitcast {ft} %f to {bits}\n  ret {bits} %r\n}}")
            for x in (0, 1):
                if op == "uitofp nneg" and x:
                    continue
                t.call(f"{v}_{x}", FP_BITS[ft, float(-x if op == "sitofp" else x)], bits, v, f"i1 {x}")
    for ft in ("float", "double"):
        for op in ("fptoui", "fptosi"):
            v = f"{op}_{ft}"
            t.section(f"{op} {ft} to i1")
            t.add(f"define i1 @{v}({ft} %x) {{\n  %r = {op} {ft} %x to i1\n  ret i1 %r\n}}")
            for label, lit, x in FPS:
                r = fptoint(op == "fptosi", x)
                if r != P:
                    t.call(f"{v}_{label}", r, "i1", v, f"{ft} {lit}")
    t.section("bitcast, ptrtoint, inttoptr")
    t.add("""
define i1 @bitcast_to_v1(i1 %x) {
  %v = bitcast i1 %x to <1 x i1>
  %r = extractelement <1 x i1> %v, i32 0
  ret i1 %r
}

define i1 @bitcast_from_v1(i1 %x) {
  %v = insertelement <1 x i1> poison, i1 %x, i32 0
  %r = bitcast <1 x i1> %v to i1
  ret i1 %r
}

; inttoptr zero-extends an integer narrower than a pointer: i1 1 is address 1,
; not address -1
define i64 @inttoptr(i1 %x) {
  %p = inttoptr i1 %x to ptr
  %r = ptrtoint ptr %p to i64
  ret i64 %r
}

; ptrtoint truncates a pointer to a narrower integer
define i1 @ptrtoint(i64 %x) {
  %p = inttoptr i64 %x to ptr
  %r = ptrtoint ptr %p to i1
  ret i1 %r
}""")
    for x in (0, 1):
        t.call(f"bitcast_to_v1_{x}", x, "i1", "bitcast_to_v1", f"i1 {x}")
        t.call(f"bitcast_from_v1_{x}", x, "i1", "bitcast_from_v1", f"i1 {x}")
        t.call(f"inttoptr_{x}", x, "i64", "inttoptr", f"i1 {x}")
    for x in (0, 1, 2, 3):
        t.call(f"ptrtoint_{x}", x & 1, "i1", "ptrtoint", f"i64 {x}")
    t.write()

